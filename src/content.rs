#![cfg_attr(not(target_arch = "wasm32"), allow(dead_code))]

pub struct Project {
    pub name: &'static str,
    pub category: &'static str,
    pub role: &'static str,
    pub summary: &'static str,
    pub problem: &'static str,
    pub built: &'static str,
    pub stack: &'static [&'static str],
    pub links: &'static [(&'static str, &'static str)],
    pub status: &'static str,
    pub image: Option<&'static str>,
}

pub enum Slide {
    Video {
        src: &'static str,
        poster: &'static str,
        label: &'static str,
        description: &'static str,
    },
    Image {
        src: &'static str,
        alt: &'static str,
        description: &'static str,
    },
}

pub struct RunPost {
    pub title: &'static str,
    pub place: &'static str,
    pub date: &'static str,
    pub stats: &'static [(&'static str, &'static str)],
    pub note: &'static str,
    pub slides: &'static [Slide],
    pub gpx: Option<(&'static str, &'static str)>,
}

pub struct Document {
    pub title: &'static str,
    pub detail: &'static str,
    pub href: &'static str,
    pub meta: &'static str,
}

pub struct Race {
    pub name: &'static str,
    pub distance: &'static str,
    pub upcoming: bool,
}

pub struct Showcase {
    pub label: &'static str,
    pub image: &'static str,
    pub href: &'static str,
    pub shape: &'static str,
    pub size: &'static str,
}

pub struct Ticket {
    pub style: &'static str,
    pub label: &'static str,
    pub title: &'static str,
    pub text: &'static str,
    pub meta: &'static [&'static str],
}

// Generated by build.rs from content/*.json, which the site editor writes.
include!(concat!(env!("OUT_DIR"), "/content.rs"));

#[cfg(test)]
mod tests {
    use std::collections::HashSet;
    use std::path::Path;

    use super::{
        ABOUT_STATEMENT, BUBBLE_LINES, CONTACT_INTRO, CONTACTS, DOCUMENTS, EDUCATION, EXPERIENCE,
        HERO_WORDS, PROJECTS, RACES, RUNS, Slide, TICKETS,
    };

    const OPTIMIZED: &str = "assets/optimized/";

    fn asset_paths() -> Vec<&'static str> {
        let mut paths = PROJECTS
            .iter()
            .filter_map(|project| project.image)
            .collect::<Vec<_>>();
        for run in RUNS {
            for slide in run.slides {
                match slide {
                    Slide::Video { src, poster, .. } => paths.extend([*src, *poster]),
                    Slide::Image { src, .. } => paths.push(src),
                }
            }
            if let Some((href, _)) = run.gpx {
                paths.push(href);
            }
        }
        paths.extend(DOCUMENTS.iter().map(|document| document.href));
        paths
    }

    fn visible_text() -> Vec<&'static str> {
        let mut text = vec![EDUCATION, CONTACT_INTRO];
        for project in PROJECTS {
            text.extend([
                project.name,
                project.category,
                project.role,
                project.summary,
                project.problem,
                project.built,
                project.status,
            ]);
            text.extend(project.stack);
        }
        for run in RUNS {
            text.extend([run.title, run.place, run.date, run.note]);
            for slide in run.slides {
                match slide {
                    Slide::Video {
                        label, description, ..
                    } => text.extend([*label, *description]),
                    Slide::Image {
                        alt, description, ..
                    } => text.extend([*alt, *description]),
                }
            }
        }
        text.extend(ABOUT_STATEMENT.iter().map(|(part, _)| *part));
        text.extend(EXPERIENCE.iter().flat_map(|(title, body)| [*title, *body]));
        text.extend(RACES.iter().flat_map(|race| [race.name, race.distance]));
        text.extend(
            BUBBLE_LINES
                .iter()
                .flat_map(|(first, second)| [*first, *second]),
        );
        text.extend(
            TICKETS
                .iter()
                .flat_map(|ticket| [ticket.label, ticket.title, ticket.text]),
        );
        text
    }

    #[test]
    fn project_names_are_nonempty_and_unique() {
        let mut names = HashSet::new();
        for project in PROJECTS {
            assert!(!project.name.trim().is_empty());
            assert!(
                names.insert(project.name),
                "duplicate project: {}",
                project.name
            );
        }
    }

    #[test]
    fn links_use_only_https() {
        let project_links = PROJECTS
            .iter()
            .flat_map(|project| project.links.iter().map(|(_, href)| *href));
        let contact_links = CONTACTS.iter().map(|(_, href)| *href);
        for href in project_links.chain(contact_links) {
            assert!(
                href.starts_with("https://") || href.starts_with("assets/docs/"),
                "unsupported link scheme: {href}"
            );
        }
    }

    #[test]
    fn referenced_assets_exist() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR"));
        for path in asset_paths() {
            assert!(!path.starts_with('/'), "asset must be relative: {path}");
            if path.starts_with(OPTIMIZED) {
                continue;
            }
            assert!(root.join(path).is_file(), "missing asset: {path}");
        }
    }

    #[test]
    fn visible_copy_has_no_dashes() {
        for text in visible_text() {
            assert!(
                !text.contains('\u{2013}') && !text.contains('\u{2014}'),
                "dash in copy: {text}"
            );
        }
    }

    #[test]
    fn hero_outlines_point_at_letters() {
        for (word, outlined) in HERO_WORDS {
            let letter = word.chars().nth(*outlined);
            assert!(
                letter.is_some_and(|letter| letter != ' '),
                "bad outline in {word}"
            );
        }
    }
}
